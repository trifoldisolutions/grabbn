async function seed() {
    const uri    = process.env.MONGODB_URI;
    const dbName = process.env.MONGODB_DB || 'grabbn';
    if (!uri) throw new Error('MONGODB_URI is not set in .env');

    await mongoose.connect(uri, { dbName });
    console.log('Connected to MongoDB');

    const existing = await FaqItem.countDocuments({ source: 'admin' });
    if (existing > 0) {
        console.log(`Skipping — ${existing} admin FAQ items already exist. Delete them first to re-seed.`);
        await mongoose.disconnect();
        return;
    }

    const docs = ITEMS.map(item => ({
        ...item,
        source:      'admin',
        status:      'published',
        publishedAt: new Date(),
    }));

    await FaqItem.insertMany(docs);
    console.log(`Seeded ${docs.length} FAQ items.`);
    await mongoose.disconnect();
}

seed().catch(err => {
    console.error(err);
    process.exit(1);
});
